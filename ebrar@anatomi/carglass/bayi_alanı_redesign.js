const bayi_alani_redesign_js = () => {
  const dropdownContainers = document.querySelectorAll(
    ".anatomi-dropdown-container"
  );

  dropdownContainers.forEach((container) => {
    const toggleButton = container.querySelector(".anatomi-dropdown-toggle");
    const dropdownMenu = container.querySelector(".anatomi-dropdown-menu");
    dropdownMenu.style.display = "none";

   toggleButton.addEventListener("click", () => {
  const isOpen = dropdownMenu.style.display === "block";

  dropdownContainers.forEach((otherContainer) => {
    const otherToggle = otherContainer.querySelector(".anatomi-dropdown-toggle");
    const otherMenu = otherContainer.querySelector(".anatomi-dropdown-menu");
    otherToggle.classList.remove("open");
    otherMenu.style.display = "none";
    otherContainer.classList.remove("anatomi-dropdown-container-active");
    otherContainer.style.gridRow = "";
  });

  if (!isOpen) {
    toggleButton.classList.add("open");
    dropdownMenu.style.display = "block";
    container.classList.add("anatomi-dropdown-container-active");

    const itemCount = dropdownMenu.querySelectorAll("li").length;
    if (itemCount > 0) {
      if (window.innerWidth <= 768) {
        container.style.gridRow = `span ${itemCount}`;
      } else {
        container.style.gridRow = `span ${itemCount}`;
      }
    }
  } else {
    toggleButton.classList.remove("open");
    dropdownMenu.style.display = "none";
    container.classList.remove("anatomi-dropdown-container-active");
    container.style.gridRow = "";
  }
});
  });

};


